#!/bin/sh
# FORESIGHT · NVIDIA Isaac Sim 6.0 assets for the G1 demo — standalone downloader.
# Needs only sh + curl (works in Termux, a-Shell, macOS, Linux). No Python, no repo files.
#
#   sh download_isaac_assets.sh [target_dir]        (default: ./isaac_assets)
#   DRY_RUN=1 sh download_isaac_assets.sh           (only report what is still missing)
#
# Downloads 3,663 files (2.70 GB) from NVIDIA's public asset bucket: the Office, Hospital, Simple Warehouse and
# Digital-Twin Warehouse scenes, the Unitree G1 (Isaac Lab + hand variants), the H1 and the pretrained G1 walking
# checkpoints. Resumable: run it again after an interruption and it skips files that are already complete.
# When it finishes, copy the whole target folder to /ml/FORESIGHT/isaac_assets/ on the workstation.
set -u
DEST="${1:-isaac_assets}"
BASE="https://omniverse-content-production.s3-us-west-2.amazonaws.com/Assets/Isaac/6.0"
PAR=6
mkdir -p "$DEST" || exit 1
command -v curl >/dev/null 2>&1 || { echo "curl not found (Termux: pkg install curl)"; exit 1; }

size_of() { if [ -f "$1" ]; then wc -c < "$1" | tr -d ' '; else echo -1; fi; }

CFG="$DEST/.curl_todo.cfg"
LIST="$DEST/.filelist"
sed -n '/^__FILES__$/,$p' "$0" | sed '1d' > "$LIST"

pass() {
  : > "$CFG"
  todo=0; todo_b=0; total=0; total_b=0
  while read -r sz key; do
    [ -n "$key" ] || continue
    total=$((total + 1)); total_b=$((total_b + sz))
    if [ "$(size_of "$DEST/$key")" != "$sz" ]; then
      todo=$((todo + 1)); todo_b=$((todo_b + sz))
      printf 'url = "%s/%s"\noutput = "%s/%s"\n' "$BASE" "$key" "$DEST" "$key" >> "$CFG"
    fi
  done < "$LIST"
  echo "$todo of $total files left ($((todo_b / 1000000)) of $((total_b / 1000000)) MB)"
}

if [ "${DRY_RUN:-0}" = 1 ]; then pass; rm -f "$CFG"; exit 0; fi

for round in 1 2 3 4 5; do
  pass
  [ "$todo" -eq 0 ] && break
  echo "== round $round: downloading"
  if curl --help all 2>/dev/null | grep -q -- '--parallel'; then
    curl -sS --fail --retry 5 --retry-delay 3 --connect-timeout 30 --create-dirs \
         --parallel --parallel-max "$PAR" -K "$CFG" || true
  else
    curl -sS --fail --retry 5 --retry-delay 3 --connect-timeout 30 --create-dirs -K "$CFG" || true
  fi
done

pass
rm -f "$CFG"
if [ "$todo" -eq 0 ]; then
  echo "done: all files complete in $DEST"
else
  echo "incomplete: $todo files still missing; run the script again"
  exit 1
fi
exit 0
